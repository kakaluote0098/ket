const fs = require('fs');

function escapeSingle(str) {
  return str.replace(/'/g, "\\'");
}

function makeWord(prefix, w) {
  const safeId = w.english.replace(/\s+/g, '_').replace(/[^a-zA-Z0-9_]/g, '');
  const id = `${prefix}_${safeId}`;
  return `          { id: '${id}', english: '${escapeSingle(w.english)}', chinese: '${escapeSingle(w.chinese)}', phonetic: '${escapeSingle(w.phonetic)}', example: '${escapeSingle(w.example)}' }`;
}

function makeCategory(prefix, cat) {
  const wordsLines = cat.words.map((w) => makeWord(prefix, w)).join(',\n');
  return `      {
        id: '${prefix}_${cat.id}',
        title: '${escapeSingle(cat.title)}',
        icon: '${cat.icon}',
        words: [
${wordsLines},
        ],
      },`;
}

function makeGrade(grade, prefix) {
  const catLines = grade.categories.map((c) => makeCategory(prefix, c)).join('\n');
  return `  {
    key: '${grade.key}',
    label: '${escapeSingle(grade.label)}',
    description: '${escapeSingle(grade.description)}',
    categories: [
${catLines}
    ],
  },`;
}

